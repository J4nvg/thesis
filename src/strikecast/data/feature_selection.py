"""Top-k feature selection by LightGBM gain importance.

Behaviour-preserving port of the feature-selection step that was copy-pasted
into every legacy notebook (refactor plan sec. 2.2 stage 6, sec. 2.3 row
"Feature selection", flag F8, golden level G).

Provenance of the reproduced code paths
---------------------------------------
``src/prevalent_functions.py::get_top_100_from_lgbm``
    the hurdle pipeline (``final_hurdle.ipynb`` cells 9-11), used for both the
    Poisson regressor and the binary classifier of the ``zipoisson`` family.
``_regression_GBDT.ipynb`` cell 28
    the inline block of the count family (``countreg``).
``_diff_regression.py`` lines ~485-545
    the inline block of the differenced family (``diffreg``).
``src/feature_tools.py::clean_feature_names``
    name parsing, copied verbatim into :func:`parse_feature_names`.
``src/general_tools.py::subset_safe``
    the component subsetting applied downstream, copied into
    :func:`subset_safe`.

The three legacy copies differ *only* in the LightGBM kwargs they pass; those
differences are captured as configuration (``FeatureSelectionConfig``), never
as branches.  Documented quirks that are deliberately preserved:

Q1  The gain frame is built from ``fitted_model.lagged_feature_names``, which
    also contains the darts-generated cyclic encoder columns and the encoded
    static covariates.  Those never match one of the four suffixes and are
    simply dropped by :func:`parse_feature_names` (with a log line).
Q2  ``clean_feature_names`` splits on the *first* occurrence of a suffix
    anywhere in the name, not on a trailing ``_<suffix>_lag<n>`` pattern.  A
    base feature whose own name contains e.g. ``_target`` would be truncated.
Q3  ``top_k`` counts *lagged* feature names, not base features.  Because every
    past covariate appears once per entry of ``lags_past_covariates`` (3 by
    default), the number of surviving base features is much smaller than
    ``top_k`` -- 52 past + 8 future for ``diffreg``, for example.
Q4  The legacy sort is ``DataFrame.sort_values(..., ascending=False)`` with
    pandas' default (non-stable) quicksort.  Ties among zero-gain features are
    therefore broken arbitrarily but deterministically for a given frame.
Q5  The count family names the aggregate column ``agg_gain`` while the hurdle
    family names it ``mean_gain``.  Both names are emitted, with identical
    values, so either legacy caller keeps working.
Q6  ``get_top_100_from_lgbm`` writes ``prelimFeatureImportanceRegressor.csv``
    into the working directory and prints the top 20.  That side effect is
    dropped here (the ranking is returned instead); nothing downstream read
    the file.
Q7  The hurdle *regressor* selection fits with positive-only sample weights
    (``make_positive_only_weights``); the classifier selection and both inline
    blocks fit unweighted.  Hence the optional ``sample_weight`` argument.
Q8  The ``diffreg`` selection is fitted on the **level** target
    (``train_target``), not on the differenced one, even though every model in
    that family trains on the differenced target.
Q9  The count family fitted the selection model with ``device_type="gpu"``.
    LightGBM's GPU histogram builder can rank near-tied features differently
    from the CPU builder, so a CPU re-run is not guaranteed to be bit-identical.
Q10 **The legacy selection is not reproducible at all.** The upstream helpers
    ``get_engineered_features`` and ``split_future_and_past_cov`` build their
    column lists with ``list(set(...))``, so the *order* of the covariate
    columns -- and hence the column order of LightGBM's design matrix, and
    hence how it breaks ties between equally good splits -- depends on
    ``PYTHONHASHSEED``.  Two runs of the identical script in separate
    processes disagree (measured: max ``|delta mean_gain|`` ~48, 54 vs 55
    surviving past covariates); two runs under ``PYTHONHASHSEED=0`` are
    bit-identical.  The legacy runs never pinned the seed, so the cached sets
    in ``features/*_saved_sets.pkl`` cannot be regenerated by anyone.  This
    module does not fix it (behaviour-preserving refactor); the fix belongs
    upstream, in whatever replaces those two helpers, and the cached sets
    should be treated as data to load rather than output to reproduce.
"""

