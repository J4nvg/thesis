# legacy copies
# --------------------------------------------------------------------------- #
def parse_feature_names(input_list: list) -> dict:
    """Copy of ``src/feature_tools.py::clean_feature_names``.

    Verbatim apart from the unmatched-name ``print`` becoming a
    ``logging.debug`` call.  See quirks Q1/Q2.
    """
    r_dict = {
        "futcov_features_base": set(),
        "futcov_features_actual": set(),
        "pastcov_features_base": set(),
        "pastcov_features_actual": set(),
        "statcov_features_base": set(),
        "statcov_features_actual": set(),
        "target_features_base": set(),
        "target_features_actual": set(),
        "features_base": set(),
        "actual_features": set(),
    }

    if not input_list:
        return r_dict

    # Define the suffixes to look for
    suffixes = ["_pastcov", "_futcov", "_statcov", "_target"]

    for variable in input_list:
        matched = False
        for suffix in suffixes:
            if suffix in variable:
                var = variable.split(suffix)[0]
                prefix = suffix.strip("_")  # turns '_pastcov' into 'pastcov'

                r_dict["features_base"].add(var)
                r_dict["actual_features"].add(variable)
                r_dict[f"{prefix}_features_base"].add(var)
                r_dict[f"{prefix}_features_actual"].add(variable)

                matched = True
                break  # Stop searching suffixes once a match is found

        if not matched:
            logger.debug("'%s': none of pastcov, futcov, statcov, target ..", variable)

    return r_dict


def subset_safe(ts, wanted):
    """Copy of ``src/general_tools.py::subset_safe``.

    Keeps only the wanted components that the series actually has, in the
    iteration order of ``wanted``.  Note that the legacy callers pass a *set*,
    so the resulting component order is non-deterministic across runs.
    """
    available = set(ts.components)
    return ts[[c for c in wanted if c in available]]


# --------------------------------------------------------------------------- #
# ranking
# --------------------------------------------------------------------------- #
def rank_features_by_gain(model) -> pd.DataFrame:
    """Per-horizon LightGBM gain importances, aggregated and sorted.

    Reproduces the frame built by ``get_top_100_from_lgbm`` / the inline FS
    blocks, without the CSV side effect (Q6).  Columns:
    ``Feature``, ``h1_gain`` ... ``hH_gain``, ``mean_gain``, ``agg_gain``
    (Q5: the last two are identical; the legacy copies used one name each).
    """
    gain_imps: dict[str, Any] = {"Feature": model.lagged_feature_names}
    underlying_model = model.model
    estimators = (
        underlying_model.estimators_
        if hasattr(underlying_model, "estimators_")
        else [underlying_model]
    )
    for h, est in enumerate(estimators, start=1):
        gain_imps[f"h{h}_gain"] = est.booster_.feature_importance(importance_type="gain")

    df_gain = pd.DataFrame(gain_imps)
    # Legacy: `df_gain.filter(like="_gain").mean(axis=1)` (hurdle) and
    # `df_gain.iloc[:, 1:].mean(axis=1)` (inline blocks) -- identical at this
    # point, both average the per-horizon gain columns only.
    df_gain["mean_gain"] = df_gain.filter(like="_gain").mean(axis=1)
    df_gain["agg_gain"] = df_gain["mean_gain"]
    df_gain = df_gain.sort_values("mean_gain", ascending=False).reset_index(drop=True)
    return df_gain


# --------------------------------------------------------------------------- #
# result container
# --------------------------------------------------------------------------- #
@dataclass
class FeatureSelection:
    """Result of :func:`select_top_k`."""

    gain_table: pd.DataFrame
    selected: dict
    top_features: list[str]
    config: FeatureSelectionConfig
    available_past: list[str] = field(default_factory=list)
    available_future: list[str] = field(default_factory=list)

    @property
    def past_keep(self) -> list[str]:
        """Surviving past-covariate components, sorted.

        Intersected with the components the covariate series actually has,
        which is what the legacy ``subset_safe`` call did downstream and what
        the cached ``*_saved_sets.pkl`` therefore contains.  Without it the
        darts cyclic-encoder columns (``darts_enc_fc_cyc_*``) would leak in:
        they carry a ``_futcov`` suffix in ``lagged_feature_names`` but are not
        components of any input series.
        """
        return self._keep("pastcov_features_base", self.available_past)

    @property
    def future_keep(self) -> list[str]:
        """Surviving future-covariate components, sorted (see :attr:`past_keep`)."""
        return self._keep("futcov_features_base", self.available_future)

    def _keep(self, key: str, available: list[str]) -> list[str]:
        base = self.selected[key]
        if not available:
            return sorted(base)
        return sorted(base & set(available))

    def to_json(self, path: str | Path) -> Path:
        """Write the selection (not the gain table) as JSON."""
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "config": self.config.model_dump(mode="json"),
            # JSON has no tuples, and darts reads `lags_future_covariates` as a
            # (past, future) *tuple* but as an explicit list of lags when given
            # a list -- two very different models. Remember which kwargs were
            # tuples so `from_json` can restore them.
            "tuple_kwargs": sorted(
                k for k, v in self.config.model_kwargs.items() if isinstance(v, tuple)
            ),
            "available_past": list(self.available_past),
            "available_future": list(self.available_future),
            "top_features": list(self.top_features),
            "selected": {k: sorted(self.selected[k]) for k in LEGACY_SELECTION_KEYS},
            "past_keep": self.past_keep,
            "future_keep": self.future_keep,
        }
        path.write_text(json.dumps(payload, indent=2, sort_keys=False), encoding="utf-8")
        return path

    @classmethod
    def from_json(cls, path: str | Path) -> FeatureSelection:
        """Read back a selection written by :meth:`to_json`.

        ``gain_table`` comes back empty -- it is not persisted.
        """
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
        selected = {k: set(v) for k, v in payload["selected"].items()}
        config_payload = dict(payload["config"])
        model_kwargs = dict(config_payload.get("model_kwargs", {}))
        for key in payload.get("tuple_kwargs", []):
            if key in model_kwargs:
                model_kwargs[key] = tuple(model_kwargs[key])
        config_payload["model_kwargs"] = model_kwargs
        return cls(
            gain_table=pd.DataFrame(),
            selected=selected,
            top_features=list(payload["top_features"]),
            config=FeatureSelectionConfig(**config_payload),
            available_past=list(payload.get("available_past", [])),
            available_future=list(payload.get("available_future", [])),
        )


# --------------------------------------------------------------------------- #
# the FS step itself
# --------------------------------------------------------------------------- #
def select_top_k(
    train_target,
    past_covs,
    future_covs,
    config: FeatureSelectionConfig,
    *,
    sample_weight=None,
) -> FeatureSelection:
    """Fit one LightGBM on everything and keep the top-``k`` lagged features.

    Args:
        train_target: the training target series (list of ``TimeSeries``).  For
            the ``diffreg`` family this is the **level** target (Q8).
        past_covs: full-length past covariates, as returned by
            ``get_covs_and_encodings``.
        future_covs: full-length future covariates.
        config: the per-family kwargs.
        sample_weight: optional, only the hurdle regressor used it (Q7).
    """
    model = config.build_model()
    fit_kwargs: dict[str, Any] = {
        "series": train_target,
        "past_covariates": past_covs,
        "future_covariates": future_covs,
    }
    if sample_weight is not None:
        fit_kwargs["sample_weight"] = sample_weight
    model.fit(**fit_kwargs)

    gain_table = rank_features_by_gain(model)
    top_features = gain_table.head(config.top_k)["Feature"].to_list()
    selected = parse_feature_names(top_features)
    return FeatureSelection(
        gain_table=gain_table,
        selected=selected,
        top_features=top_features,
        config=config,
        available_past=_components(past_covs),
        available_future=_components(future_covs),
    )


def _components(covs) -> list[str]:
    """Component names of a (list of) darts ``TimeSeries``; [] when absent."""
    if covs is None:
        return []
    first = covs[0] if isinstance(covs, (list, tuple)) else covs
    return [str(c) for c in first.components]


# --------------------------------------------------------------------------- #
# the three legacy configurations, extracted verbatim
# --------------------------------------------------------------------------- #
def legacy_common_kwargs(input_lags: int = 7, output_chunk_len: int = 7) -> dict[str, Any]:
    """Copy of ``src/prevalent_functions.py::get_common_kwargs``.

    All three families call it with its defaults, so all three share
    ``lags=7``, ``lags_past_covariates=[-1, -7, -14]``,
    ``lags_future_covariates=(2, 7)`` and the cyclic encoders.
    """
    return dict(
        lags=input_lags,
        lags_past_covariates=[-1, -7, -14],
        lags_future_covariates=(2, output_chunk_len),
        output_chunk_length=output_chunk_len,
        output_chunk_shift=0,
        add_encoders={
            "cyclic": {"future": ["month", "week", "dayofyear", "dayofweek", "day"]},
        },
    )


def countreg_config(*, device_type: str = "gpu", num_threads: int | None = None):
    """``_regression_GBDT.ipynb`` cell 28 -> ``build_regressor("lightgbm_tweedie")``.

    Note the family's selection model is the **tweedie** default builder, not
    the poisson one.  Because ``objective`` is constrained to the three values
    the refactor plan lists, ``tweedie`` travels in ``model_kwargs``; the
    ``objective`` field carries the family's headline objective (``poisson``)
    and is overridden here.  ``device_type`` defaults to the legacy ``"gpu"``;
    pass ``"cpu"`` to re-run on a machine without a GPU (Q9).
    """
    kwargs: dict[str, Any] = {
        **legacy_common_kwargs(),
        "objective": "tweedie",
        "num_leaves": 31,
        "max_depth": 5,
        "min_child_samples": 30,
        "subsample": 0.8,
        "colsample_bytree": 0.8,
        "learning_rate": 0.05,
        "n_estimators": 500,
        "reg_alpha": 0.0,
        "reg_lambda": 0.0,
        "tweedie_variance_power": 1.5,
        "random_state": 42,
        "verbose": -1,
        "device_type": device_type,
        "force_col_wise": True,
    }
    if num_threads is not None:
        # The legacy builder has `num_threads` commented out (GPU run).
        kwargs["num_threads"] = num_threads
    return FeatureSelectionConfig(top_k=100, objective="poisson", kind="regressor",
                                  model_kwargs=kwargs)


def diffreg_config(*, device_type: str = "cpu", num_threads: int = 4):
    """``_diff_regression.py`` -> ``build_regressor("lightgbm")``.

    ``available_threads`` is hard-coded to ``4`` in that script (it does *not*
    call ``get_available_threads()`` like the other two), and ``multi_models``
    is passed explicitly (it is the darts default anyway).
    """
    return FeatureSelectionConfig(
        top_k=100,
        objective="regression",
        kind="regressor",
        model_kwargs={
            **legacy_common_kwargs(),
            "multi_models": True,
            "num_leaves": 31,
            "max_depth": 5,
            "min_child_samples": 30,
            "subsample": 0.8,
            "colsample_bytree": 0.8,
            "learning_rate": 0.05,
            "n_estimators": 500,
            "reg_alpha": 0.0,
            "reg_lambda": 0.0,
            "random_state": 42,
            "verbose": -1,
            "device_type": device_type,
            "num_threads": num_threads,
            "force_col_wise": True,
        },
    )


def zipoisson_regressor_config():
    """``final_hurdle.ipynb`` cell 9 -> ``regressor_feature_selection``.

    Only the shared skeleton, the objective and the seed -- every LightGBM
    hyper-parameter is left at its library default, and no device/thread kwarg
    is passed.  Fitted with positive-only sample weights (Q7).
    """
    return FeatureSelectionConfig(
        top_k=100,
        objective="poisson",
        kind="regressor",
        model_kwargs={**legacy_common_kwargs(), "random_state": 42},
    )


def zipoisson_classifier_config():
    """``final_hurdle.ipynb`` cell 9 -> ``event_classifier_feature_selection``."""
    return FeatureSelectionConfig(
        top_k=100,
        objective="binary",
        kind="classifier",
        model_kwargs={**legacy_common_kwargs(), "is_unbalance": True, "random_state": 42},
    )
